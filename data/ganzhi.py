def get_nayin(ganzhi: str) -> str:
    """查询纳音五行（如 甲子 → 海中金）"""
    try:
        idx = GANZHI_60.index(ganzhi)
    except ValueError:
        return "—"
    return NAYIN_60[idx // 2]


def shishen(day_gan: str, other_gan: str) -> str:
    """以日干为主，求其它天干相对日干的十神"""
    if day_gan not in STEM_WUXING or other_gan not in STEM_WUXING:
        return "—"
    same_yinyang = STEM_YINYANG[day_gan] == STEM_YINYANG[other_gan]
    wx_day = STEM_WUXING[day_gan]
    wx_other = STEM_WUXING[other_gan]
    if wx_other == wx_day:
        return "比肩" if same_yinyang else "劫财"
    if SHENG.get(wx_other) == wx_day:      # 他生我
        return "偏印" if same_yinyang else "正印"
    if SHENG.get(wx_day) == wx_other:      # 我生他
        return "食神" if same_yinyang else "伤官"
    if KE.get(wx_day) == wx_other:         # 我克他
        return "偏财" if same_yinyang else "正财"
    if KE.get(wx_other) == wx_day:         # 他克我
        return "七杀" if same_yinyang else "正官"
    return "—"


def shishen_wuxing(day_gan: str, other_gan: str) -> str:
    """十神对应的五行属性"""
    ss = shishen(day_gan, other_gan)
    return STEM_WUXING[other_gan]


